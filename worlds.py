"""Which world is the stream fitted into?

The "fit an unrelated scene" control for attenuation.py, transplanted. If a world
learned from Janus's two synthetic images (attenuation.py's rings A and cross B,
generated by its own formulas, converted to grey) explains unseen photographs as
well as a world learned from natural photographs, then the fitting is painting
with a flexible field, not perceiving through a learned world.

natural  64 atoms learned from training-photo patches (Model 6's dictionary)
janus    64 atoms learned the same way from patches of attenuation.py's A and B only
random   64 random zero-mean unit atoms (no world at all)
"""
import numpy as np

from models import fit_dictionary


def janus_patterns(res=128):
    """attenuation.py's _make_synthetic_pattern(0) and (1), unchanged formulas, to grey."""
    y, x = np.meshgrid(np.linspace(-1, 1, res), np.linspace(-1, 1, res), indexing="ij")
    r = np.sqrt(x ** 2 + y ** 2)
    out = []
    for mode in (0, 1):
        img = np.zeros((res, res, 3), np.float32)
        if mode == 0:
            rings = 0.5 + 0.5 * np.cos(r * 18.0)
            img[..., 0] = np.clip(rings * (0.6 + 0.4 * x), 0, 1)
            img[..., 1] = np.clip(0.4 * (1 - r) + 0.3 * rings, 0, 1)
            img[..., 2] = np.clip(0.2 + 0.6 * (y > 0) * rings, 0, 1)
        else:
            cross = ((np.abs(x) < 0.22) | (np.abs(y) < 0.22)).astype(np.float32)
            check = ((np.sin(x * 28) * np.sin(y * 28)) > 0).astype(np.float32)
            img[..., 0] = np.clip(0.15 + 0.7 * (1 - cross) * check, 0, 1)
            img[..., 1] = np.clip(0.8 * cross + 0.2 * check, 0, 1)
            img[..., 2] = np.clip(0.9 * cross + 0.4 * (1 - r), 0, 1)
        out.append(img @ np.array([0.299, 0.587, 0.114], np.float32))
    return out


def janus_dictionary(n_atoms=64, seed=0):
    imgs = janus_patterns()
    crops = []
    rng = np.random.default_rng(seed)
    for im in imgs:
        for _ in range(400):
            i, j = rng.integers(0, im.shape[0] - 32, 2)
            crops.append(im[i:i + 32, j:j + 32])
    return fit_dictionary(np.array(crops), n_atoms=n_atoms, seed=seed)


def random_dictionary(n_atoms=64, seed=0):
    rng = np.random.default_rng(seed)
    D = rng.standard_normal((n_atoms, 8, 8))
    D -= D.mean((1, 2), keepdims=True)
    return D / np.linalg.norm(D.reshape(n_atoms, -1), axis=1)[:, None, None]
